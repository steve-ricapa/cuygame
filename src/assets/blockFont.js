// Los acentos se simplifican a la letra base (la fuente no los dibuja aparte).
const ACCENTS = {
  Á: 'A', À: 'A', Ä: 'A', Â: 'A',
  É: 'E', È: 'E', Ë: 'E', Ê: 'E',
  Í: 'I', Ì: 'I', Ï: 'I', Î: 'I',
  Ó: 'O', Ò: 'O', Ö: 'O', Ô: 'O',
  Ú: 'U', Ù: 'U', Ü: 'U', Û: 'U',
  'Ç': 'C', 'Ñ': 'N_TILDE',
};

// «<3» se convierte en un corazón de bloques.
const HEART_TOKEN = '\u0001';

function normalizeChar(ch) {
  if (ch === HEART_TOKEN) return 'HEART';
  if (ch === 'Ñ') return 'N_TILDE';
  return ACCENTS[ch] || ch;
}

/**
 * Convierte un texto en la lista de celdas que lo forman.
 * Devuelve `{ cells: [{ dx, dy }], width }` con dx/dy en columnas/filas
 * (dy va de 0 a 4, de arriba a abajo). El texto «<3» se dibuja como corazón.
 */
export function rasterizeText(text) {
  const source = String(text ?? '')
    .toUpperCase()
    .replace(/<3/g, HEART_TOKEN);
  const chars = source.split('');
  const cells = [];
  let x = 0;
  for (const raw of chars) {
    const ch = normalizeChar(raw);
    const glyph = FONT[ch] || FONT[' '];
    const w = glyph[0].length;
    for (let r = 0; r < glyph.length; r++) {
      for (let c = 0; c < w; c++) {
        if (glyph[r][c] === '#') cells.push({ dx: x + c, dy: r });
      }
    }
    x += w + 1; // un bloque de separación entre glifos
  }
  return { cells, width: Math.max(0, x - 1) };
}

